"""Pure file helpers (no Home Assistant imports): atomic writes, the generated theme file
with backup of foreign files, the wallpaper upload folder with quota, and removal."""

from __future__ import annotations

import os
import re
import shutil
import tempfile
import time
from typing import Any

try:
    from . import images as img
except ImportError:  # standalone tests
    import images as img  # type: ignore[no-redef]

GENERATED_MARK = "# Generated by Zoosh"
_LEGACY_MARKS = ("# Generated by the Zoosh integration",)
_TOP_KEY_RE = re.compile(r'^"?Zoosh(?: - [A-Za-z0-9 _-]{1,40})?"?:\s*$')


def is_generated(text: str) -> bool:
    """True when the file was written by Zoosh: the header, a legacy header, or (for files
    from earlier versions) a first theme key called "Zoosh" or "Zoosh - <name>"."""
    head = text[:2000]
    if GENERATED_MARK in head or any(m in head for m in _LEGACY_MARKS):
        return True
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        return bool(_TOP_KEY_RE.match(line))
    return False


def write_atomic(path: str, data: bytes) -> None:
    """Write data to path via a temp file in the same folder, then replace."""
    folder = os.path.dirname(path)
    os.makedirs(folder, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=folder, prefix=".zoosh_", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def write_theme_file(path: str, data: bytes) -> str | None:
    """Write the generated theme file. A file that exists but was not written by Zoosh is
    copied to <name>.bak-<timestamp> first. Returns the backup file name or None."""
    backup = None
    if os.path.isfile(path):
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                existing = handle.read(200_000)
        except OSError:
            existing = ""
        if existing and not is_generated(existing):
            backup = f"{path}.bak-{time.strftime('%Y%m%d-%H%M%S')}"
            shutil.copy2(path, backup)
    write_atomic(path, data)
    return os.path.basename(backup) if backup else None


def remove_theme_file(path: str) -> bool:
    """Delete the theme file only if Zoosh wrote it."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            text = handle.read(200_000)
    except OSError:
        return False
    if not is_generated(text):
        return False
    os.unlink(path)
    return True


def list_images(folder: str) -> list[str]:
    pat = re.compile(r"[A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp)", re.IGNORECASE)
    if not os.path.isdir(folder):
        return []
    return sorted(n for n in os.listdir(folder) if pat.fullmatch(n) and os.path.isfile(os.path.join(folder, n)))


def upload_sizes(folder: str) -> dict[str, int]:
    """{name: size} of the files Zoosh created (the wallpaper-<hash> files only)."""
    out: dict[str, int] = {}
    if not os.path.isdir(folder):
        return out
    for n in os.listdir(folder):
        p = os.path.join(folder, n)
        if img.is_upload_name(n) and os.path.isfile(p):
            out[n] = os.path.getsize(p)
    return out


def store_upload(folder: str, name: str, raw: bytes) -> None:
    """Check the quota, then write. Raises ValueError (plain message) when exceeded."""
    img.check_quota(upload_sizes(folder), name, len(raw))
    write_atomic(os.path.join(folder, name), raw)


def delete_upload(folder: str, name: Any) -> bool:
    """Delete one Zoosh upload by name. Only names matching wallpaper-<12 hex>.<ext> and
    only inside folder; bundled and foreign files are never touched."""
    if not img.is_upload_name(name):
        raise ValueError("not a Zoosh upload")
    target = os.path.join(folder, name)
    if os.path.dirname(os.path.realpath(target)) != os.path.realpath(folder):
        raise ValueError("not a Zoosh upload")
    if not os.path.isfile(target) or os.path.islink(target):
        return False
    os.unlink(target)
    return True
